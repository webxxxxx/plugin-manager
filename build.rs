//! Select the compile-time memory profile.
//!
//! `MEM_LEVEL=low|middle|high` controls the hard ceilings in `src/limits.rs`.
//! Default is `high`, preserving desktop behaviour.
//!
//! The target triple is compiled into `package::target()`; keep that even when
//! the memory level is not set.

use std::env;
use std::fs::{self, File};
use std::io::Write;
use std::path::PathBuf;

use flate2::{Compression, GzBuilder};

// The console tree walker and the extension table are shared with the crate so
// the build and the runtime answer "is this a text asset?" the same way.
#[path = "src/face/console_tree.rs"]
mod console_tree;
#[path = "src/server/http/media.rs"]
mod media;

fn main() {
    let target = env::var("TARGET").expect("cargo sets TARGET for build scripts");
    println!("cargo:rustc-env=SVCD_TARGET={target}");

    println!("cargo:rerun-if-env-changed=MEM_LEVEL");
    println!("cargo:rustc-check-cfg=cfg(mem_low)");
    println!("cargo:rustc-check-cfg=cfg(mem_middle)");
    println!("cargo:rustc-check-cfg=cfg(mem_high)");

    match env::var("MEM_LEVEL").as_deref() {
        Ok("low") => println!("cargo:rustc-cfg=mem_low"),
        Ok("middle") => println!("cargo:rustc-cfg=mem_middle"),
        Ok("high") | Ok("") | Err(_) => println!("cargo:rustc-cfg=mem_high"),
        Ok(other) => panic!("MEM_LEVEL must be one of low|middle|high, got {other:?}"),
    }

    // The console ships inside the binary. Everything under
    // `src/assets/static/` is walked at build time: text formats become gzip
    // streams, images and fonts are copied as-is, and the generated manifest
    // is the only runtime view of the tree. The sources stay the single
    // readable artifact; a fixed mtime and OS byte keep the gzip bytes
    // deterministic across machines and targets.
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets manifest dir"));
    let source_dir = manifest.join("src/assets/static");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let console_dir = out_dir.join("console");
    fs::create_dir_all(&console_dir).expect("create console asset directory");
    println!("cargo:rerun-if-changed=src/assets/static");
    // Files included with `#[path]` are outside Cargo's build-script inputs.
    println!("cargo:rerun-if-changed=src/face/console_tree.rs");
    println!("cargo:rerun-if-changed=src/server/http/media.rs");

    let mut sources = Vec::new();
    console_tree::collect(&source_dir, "", &mut sources);
    sources.sort_by(|left, right| left.0.cmp(&right.0));
    assert!(
        sources.iter().any(|(relative, _)| relative == "index.html"),
        "src/assets/static/index.html is required"
    );

    let mut generated = String::from("// Generated by build.rs; do not edit.\n");
    generated.push_str("static GENERATED: &[GeneratedAsset] = &[\n");
    for (relative, source) in &sources {
        println!("cargo:rerun-if-changed={}", source.display());
        let gzip = media::for_path(relative).compressible;
        let output = if gzip {
            format!("{relative}.gz")
        } else {
            format!("{relative}.raw")
        };
        let destination = console_dir.join(&output);
        if let Some(parent) = destination.parent() {
            fs::create_dir_all(parent).expect("create console asset subdirectory");
        }
        let bytes =
            fs::read(source).unwrap_or_else(|error| panic!("read {}: {error}", source.display()));
        if gzip {
            let file = File::create(&destination).expect("create compressed console asset");
            let mut encoder = GzBuilder::new()
                .mtime(0)
                .operating_system(255)
                .write(file, Compression::best());
            encoder
                .write_all(&bytes)
                .expect("write compressed console asset");
            encoder.finish().expect("finish compressed console asset");
        } else {
            fs::write(&destination, bytes).expect("write console asset");
        }
        let encoding = if gzip { "Gzip" } else { "Identity" };
        generated.push_str(&format!(
            "    ({relative:?}, Encoding::{encoding}, include_bytes!(concat!(env!(\"OUT_DIR\"), \"/console/\", {output:?}))),\n"
        ));
    }
    generated.push_str("];\n");
    fs::write(out_dir.join("console_manifest.rs"), generated).expect("write console manifest");
}
